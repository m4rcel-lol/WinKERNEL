/* ── Console state ──────────────────────────────────────────────────────── */
#define FONT_W  8
#define FONT_H  16

static struct {
    DWORD*  Framebuffer;
    BYTE*   RawFb;
    DWORD   Width;
    DWORD   Height;
    DWORD   Pitch;         /* in bytes */
    DWORD   Bpp;
    DWORD   Cols;
    DWORD   Rows;
    DWORD   CursorCol;
    DWORD   CursorRow;
    BYTE    FgColor;
    BYTE    BgColor;
    BOOL    Initialized;
} g_Con;

static VOID _ConPutPixel(DWORD X, DWORD Y, DWORD Rgb) {
    if (!g_Con.RawFb || X >= g_Con.Width || Y >= g_Con.Height) return;
    BYTE* row = g_Con.RawFb + Y * g_Con.Pitch;
    if (g_Con.Bpp == 32) {
        ((DWORD*)row)[X] = Rgb;
    } else if (g_Con.Bpp == 24) {
        BYTE* p = row + X * 3;
        p[0] = (BYTE)(Rgb & 0xFF);
        p[1] = (BYTE)((Rgb >> 8) & 0xFF);
        p[2] = (BYTE)((Rgb >> 16) & 0xFF);
    }
}

/* ── Internal: draw one glyph at (col, row) ─────────────────────────────── */
static VOID _DrawGlyph(DWORD Col, DWORD Row, CHAR c, BYTE Fg, BYTE Bg) {
    if (!g_Con.Initialized) return;
    BYTE  idx  = (BYTE)c;
    if (idx > 127) idx = '?';

    DWORD fg_rgb = g_Palette[Fg & 0xF];
    DWORD bg_rgb = g_Palette[Bg & 0xF];

    DWORD px = Col * FONT_W;
    DWORD py = Row * FONT_H;

    for (DWORD row = 0; row < FONT_H; row++) {
        BYTE bits = g_Font[idx][row];
        for (DWORD col = 0; col < FONT_W; col++) {
            DWORD x = px + col;
            DWORD y = py + row;
            _ConPutPixel(x, y, (bits & (0x80 >> col)) ? fg_rgb : bg_rgb);
        }
    }
}

/* ── WinConsole_Init ────────────────────────────────────────────────────── */
VOID WinConsole_Init(VOID) {
    if (!g_LimineFramebufferRequest.response ||
        g_LimineFramebufferRequest.response->framebuffer_count == 0) {
        /* No framebuffer — we cannot do anything */
        g_Con.Initialized = FALSE;
        return;
    }

    struct limine_framebuffer* fb =
        g_LimineFramebufferRequest.response->framebuffers[0];
    g_Con.Bpp = (DWORD)fb->bpp;
    if (g_Con.Bpp != 32 && g_Con.Bpp != 24) {
        g_Con.Initialized = FALSE;
        g_Con.RawFb = NULL;
        return;
    }

    g_Con.RawFb        = (BYTE*)fb->address;
    g_Con.Framebuffer  = (DWORD*)fb->address;
    g_Con.Width        = (DWORD)fb->width;
    g_Con.Height       = (DWORD)fb->height;
    g_Con.Pitch        = (DWORD)fb->pitch;
    g_Con.Cols         = g_Con.Width  / FONT_W;
    g_Con.Rows         = g_Con.Height / FONT_H;
    g_Con.CursorCol    = 0;
    g_Con.CursorRow    = 0;
    g_Con.FgColor      = CON_DEFAULT_FG;
    g_Con.BgColor      = CON_DEFAULT_BG;
    g_Con.Initialized  = TRUE;

    KdClearScreen();
}

/* ── KdClearScreen ──────────────────────────────────────────────────────── */
VOID KdClearScreen(VOID) {
    if (!g_Con.Initialized || !g_Con.RawFb) return;
    DWORD bg_rgb = g_Palette[g_Con.BgColor & 0xF];
    for (DWORD y = 0; y < g_Con.Height; y++) {
        for (DWORD x = 0; x < g_Con.Width; x++) _ConPutPixel(x, y, bg_rgb);
    }
    g_Con.CursorCol = 0;
    g_Con.CursorRow = 0;
}

/* ── KdScroll — scroll up one line ─────────────────────────────────────── */
VOID KdScroll(VOID) {
    if (!g_Con.Initialized) return;
    DWORD row_bytes  = g_Con.Pitch * FONT_H;
    DWORD total_rows = g_Con.Rows;
    BYTE* fb = g_Con.RawFb;

    /* Move all rows up by one */
    RtlCopyMemory(fb, fb + row_bytes, row_bytes * (total_rows - 1));

    /* Clear the last text row */
    DWORD bg_rgb = g_Palette[g_Con.BgColor & 0xF];
    DWORD py = (total_rows - 1) * FONT_H;
    for (DWORD row = 0; row < FONT_H; row++) {
        for (DWORD x = 0; x < g_Con.Width; x++) {
            _ConPutPixel(x, py + row, bg_rgb);
        }
    }

    g_Con.CursorRow = total_rows - 1;
}

/* ── KdPutChar ──────────────────────────────────────────────────────────── */
VOID KdPutChar(CHAR c) {
    if (!g_Con.Initialized) return;

    if (c == '\n') {
        g_Con.CursorCol = 0;
        g_Con.CursorRow++;
        if (g_Con.CursorRow >= g_Con.Rows) KdScroll();
        return;
    }

    if (c == '\r') {
        g_Con.CursorCol = 0;
        return;
    }

    if (c == '\t') {
        DWORD next = (g_Con.CursorCol + 8) & ~7u;
        while (g_Con.CursorCol < next) KdPutChar(' ');
        return;
    }

    _DrawGlyph(g_Con.CursorCol, g_Con.CursorRow, c, g_Con.FgColor, g_Con.BgColor);
    g_Con.CursorCol++;

    if (g_Con.CursorCol >= g_Con.Cols) {
        g_Con.CursorCol = 0;
        g_Con.CursorRow++;
        if (g_Con.CursorRow >= g_Con.Rows) KdScroll();
    }
}

/* ── KdBackspace ────────────────────────────────────────────────────────── */
VOID KdBackspace(VOID) {
    if (!g_Con.Initialized) return;
    if (g_Con.CursorCol > 0) {
        g_Con.CursorCol--;
    } else if (g_Con.CursorRow > 0) {
        g_Con.CursorRow--;
        g_Con.CursorCol = g_Con.Cols - 1;
    }
    _DrawGlyph(g_Con.CursorCol, g_Con.CursorRow, ' ', g_Con.FgColor, g_Con.BgColor);
}

/* ── KdPrint ────────────────────────────────────────────────────────────── */
VOID KdPrint(PCSTR Text) {
    if (!Text) return;
    while (*Text) KdPutChar(*Text++);
}

/* ── KdPrintColor ───────────────────────────────────────────────────────── */
VOID KdPrintColor(PCSTR Text, BYTE Fg, BYTE Bg) {
    BYTE old_fg = g_Con.FgColor;
    BYTE old_bg = g_Con.BgColor;
    g_Con.FgColor = Fg;
    g_Con.BgColor = Bg;
    KdPrint(Text);
    g_Con.FgColor = old_fg;
    g_Con.BgColor = old_bg;
}

/* ── KdPrintf ───────────────────────────────────────────────────────────── */
VOID KdPrintf(PCSTR Format, ...) {
    char buf[1024];
    va_list args;
    va_start(args, Format);
    RtlVprintf(buf, sizeof(buf), Format, args);
    va_end(args);
    KdPrint(buf);
}

/* ── KdPrintfColor ──────────────────────────────────────────────────────── */
VOID KdPrintfColor(BYTE Fg, BYTE Bg, PCSTR Format, ...) {
    char buf[1024];
    va_list args;
    va_start(args, Format);
    RtlVprintf(buf, sizeof(buf), Format, args);
    va_end(args);
    KdPrintColor(buf, Fg, Bg);
}

/* ── Color / cursor accessors ───────────────────────────────────────────── */
VOID KdSetColor(BYTE Fg, BYTE Bg) { g_Con.FgColor = Fg; g_Con.BgColor = Bg; }
VOID KdGetColor(BYTE* Fg, BYTE* Bg) { if (Fg) *Fg = g_Con.FgColor; if (Bg) *Bg = g_Con.BgColor; }
VOID KdMoveCursor(DWORD Col, DWORD Row) { g_Con.CursorCol = Col; g_Con.CursorRow = Row; }
VOID KdGetCursor(DWORD* Col, DWORD* Row) { if (Col) *Col = g_Con.CursorCol; if (Row) *Row = g_Con.CursorRow; }
DWORD KdGetCols(VOID) { return g_Con.Cols; }
DWORD KdGetRows(VOID) { return g_Con.Rows; }
